#!/usr/bin/env python3
"""Generate the tool tables in README.md from the Brewfile.

Source of truth: the Brewfile. Section headings (`# ── Name ──`) become
README sections. The inline comment on each line becomes "What for"; when a
line has no comment, the Homebrew description is used. Homepages and
descriptions come from `brew info --json=v2`, so every link is traceable.

Usage:
  scripts/gen-tools.py          # rewrite README.md between the markers
  scripts/gen-tools.py --check  # exit 1 if README.md is out of date
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BREWFILE = ROOT / "Brewfile"
README = ROOT / "README.md"
START, END = "<!-- tools:start -->", "<!-- tools:end -->"

SECTION = re.compile(r"^# ── (.+?) ─")
ENTRY = re.compile(r'^(brew|cask|mas|vscode|tap) "([^"]+)"((?:,\s*[^#]+?)?)\s*(?:#\s*(.*))?$')


def parse_brewfile():
    sections, taps, current = [], {}, None
    for line in BREWFILE.read_text().splitlines():
        if m := SECTION.match(line):
            current = {"title": m.group(1).strip(), "items": []}
            sections.append(current)
            continue
        if m := ENTRY.match(line.strip()):
            kind, name, opts, note = m.groups()
            mas_id = (re.search(r"id:\s*(\d+)", opts) or [None, None])[1]
            if kind == "tap":
                taps[name] = None
            elif current is not None:
                current["items"].append({"kind": kind, "name": name, "id": mas_id, "note": (note or "").strip()})
    return [s for s in sections if s["items"]], taps


def brew_json(flag, names):
    if not names:
        return []
    out = subprocess.run(["brew", "info", "--json=v2", flag, *names], check=True, capture_output=True, text=True).stdout
    return json.loads(out)["formulae" if flag == "--formula" else "casks"]


def tap_remotes(taps):
    if not taps:
        return {}
    out = subprocess.run(["brew", "tap-info", "--json", *taps], check=True, capture_output=True, text=True).stdout
    return {t["name"]: t["remote"] for t in json.loads(out)}


def package_url(kind, info, remotes):
    tap = info.get("tap") or ""
    if tap in ("homebrew/core", "homebrew/cask"):
        name = info["name"] if kind == "brew" else info["token"]
        return f"https://formulae.brew.sh/{'formula' if kind == 'brew' else 'cask'}/{name}"
    return remotes.get(tap, f"https://github.com/{tap}")


def esc(text):
    return text.replace("|", "\\|")


def render(sections, taps):
    items = [i for s in sections for i in s["items"]]
    formulae = {f["full_name"]: f for f in brew_json("--formula", [i["name"] for i in items if i["kind"] == "brew"])}
    casks = {c["full_token"]: c for c in brew_json("--cask", [i["name"] for i in items if i["kind"] == "cask"])}
    remotes = tap_remotes(list(taps))

    out = [START, "", "<!-- Generated by scripts/gen-tools.py from the Brewfile. Do not edit by hand. -->", ""]
    for s in sections:
        out += [f"### {s['title']}", ""]
        if any(i["kind"] == "mas" for i in s["items"]):
            out += ["Needs an App Store sign-in. `brew bundle` installs them with [mas](https://github.com/mas-cli/mas).", ""]
        out += ["| Tool | Install | What for |", "| --- | --- | --- |"]
        for i in s["items"]:
            kind, name, note = i["kind"], i["name"], i["note"]
            if kind == "brew":
                info = formulae[name]
                label, home, desc = info["name"], info["homepage"], info["desc"]
                cmd, pkg = f"brew install {name}", package_url(kind, info, remotes)
            elif kind == "cask":
                info = casks[name]
                label, home, desc = (info["name"] or [name])[0], info["homepage"], info["desc"]
                cmd, pkg = f"brew install --cask {name}", package_url(kind, info, remotes)
            elif kind == "mas":
                label, desc = name, ""
                home = pkg = f"https://apps.apple.com/app/id{i['id']}"
                cmd = f"mas install {i['id']}"
            else:  # vscode
                label, desc = name, ""
                home = pkg = f"https://marketplace.visualstudio.com/items?itemName={name}"
                cmd = f"code --install-extension {name}"
            what = note or desc or ""
            out.append(f"| [{esc(label)}]({home}) | [`{cmd}`]({pkg}) | {esc(what)} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    sections, taps = parse_brewfile()
    text = README.read_text()
    if START not in text or END not in text:
        sys.exit(f"README.md needs the markers {START} and {END}")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    new = before + render(sections, taps) + after
    if "--check" in sys.argv:
        if new != text:
            sys.exit("README.md tool tables are out of date. Run scripts/gen-tools.py")
        print("README.md tool tables are up to date.")
        return
    README.write_text(new)
    print("README.md tool tables updated.")


if __name__ == "__main__":
    main()
